import Foundation

/// 음높이와 상대 길이만 가진 최소 단위 (155절).
///
/// **왜 따로 두는가**: 악보에서 읽은 음과 부른 음을 같은 자리에서 비교하려면 둘을 같은
/// 타입으로 말해야 한다. `MelodySegmenter.SegmentedNote`는 온셋 시각·신뢰도까지 들고 있어
/// 악보 쪽에는 채울 수 없는 값이 있고, 조옮김 추정에 필요한 건 "무슨 음을 얼마나 오래"뿐이다.
///
/// 길이의 단위는 쓰는 쪽이 정한다 — 악보에서는 4분음표 = 1.0인 상대값, 부른 음에서는 초다.
/// 조옮김 추정은 **비율만** 쓰므로(길이가 긴 음에 더 큰 표를 준다) 단위가 달라도 된다.
struct PitchedNote: Equatable {
    let midiNote: Int
    let duration: Double
}
